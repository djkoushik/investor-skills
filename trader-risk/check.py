#!/usr/bin/env python3
"""Pre-trade risk check for trader-risk (NSE / Zerodha Kite). Standard library only, no network.

Reads the proposed orders (trader/orders.json) and checks every one against
your rules (trader/config.json), your account (trader/portfolio.json),
prices (trader/prices.json) and what was placed today (trader/state/broker.json).
Each order gets PASS or BLOCK with the reasons. Orders are checked in file
order as if each PASS had filled, so buys that are fine one by one but break
a limit together are caught.

    python3 check.py                                 # the trader/ files, writes trader/state/risk.json
    python3 check.py --now "2026-10-26 10:15"        # pin the clock (India time)
    python3 check.py --orders trader/orders.json --json
    python3 check.py --no-write                      # check without recording the verdicts

Entries and exits. An ENTRY opens or adds to a position (a buy, or a sell
that would go short). An EXIT only reduces what you hold. Getting out must
always be possible: an exit is checked for format, asset and short sales
only; every other rule turns into a warning for it.

What blocks an order (every order):

  format        missing symbol or side, no whole-share qty, a limit order
                without a limit price, an SL order without a trigger, unknown
                type, a price off the Rs 0.05 tick, a bracket that misses a leg
  asset         anything that is not an NSE / BSE cash-segment equity or ETF:
                futures and options symbols (like NIFTY26OCTFUT) are blocked
  product       CNC (delivery) is a warning, MIS is the intraday product
  short         selling more than you hold, unless "allow_short": true
                (intraday short selling is allowed on MIS, but it is off here by default)

What blocks an entry (on top):

  blocked       a ticker on your "blocked" list
  size          under min_order_inr, over max_order_inr
  position      the stock would be over max_position_pct of the account
  cash          the buy needs more than your cash (MIS leverage is not assumed
                unless "allow_margin": true) or dips into your cash buffer
  duplicate     the same symbol and side twice in this batch, or already
                placed today (trader/state/broker.json)
  daily limit   max_orders_per_day orders placed today
  stop          no stop while "require_stop": true; a stop on the wrong side of the entry;
                a stop below the lower circuit (it could never trigger)
  loss          qty x (entry - stop) over max_loss_per_trade_inr
  reward:risk   (target - entry) / (entry - stop) under min_reward_risk
  cost          the round-trip charges (brokerage, STT, GST ...) eat more than
                max_cost_r of the risk (default 0.5R): a trade that must clear
                its own costs first
  daily loss    the max losses at the stops of today's entries plus this one
                over max_daily_loss_inr
  trades        max_trades_per_day entries already placed today
  window        before no_entries_before or after no_entries_after (India time),
                or the market is closed (weekend, NSE holiday, outside 9:15 to 15:30)

Exit code 0 when every order passes, 1 when any order is blocked.
The verdicts go to trader/state/risk.json with a fingerprint of each order,
so trader-broker only shows an order as ready if THIS exact order passed today.
"""

