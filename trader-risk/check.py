PRODUCTS = {"MIS", "CNC"}
EXCHANGES = {"NSE", "BSE"}
DERIV = re.compile(r"(\d{2}(JAN|FEB|MAR|APR|MAY|JUN|JUL|AUG|SEP|OCT|NOV|DEC)|\d(FUT|CE|PE)$)")
